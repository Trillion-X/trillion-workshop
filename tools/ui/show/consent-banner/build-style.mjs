// tools/ui/show/consent-banner/build-style.mjs
//
// Writes consent-banner-style.mjs from consent-banner.css, so the bar's stylesheet is a string inside the module. A bundled site
// carries the string with the part and never needs the .css file beside it. consent-banner.css stays the one source: edit it,
// then run this again. consent-banner.test.mjs fails when the generated module is out of date.
// usage: node tools/ui/show/consent-banner/build-style.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export function styleModuleOf(css) {
  return `// Generated by build-style.mjs from consent-banner.css. Edit the .css, then run build-style.mjs again.\nexport const CONSENT_BANNER_CSS = ${JSON.stringify(css)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = readFileSync(new URL('./consent-banner.css', import.meta.url), 'utf8');
  writeFileSync(new URL('./consent-banner-style.mjs', import.meta.url), styleModuleOf(css));
}

const FIGURE_TAGS = new Set(["svg", "g", "path", "circle", "ellipse", "text", "defs", "filter", "feGaussianBlur", "linearGradient", "radialGradient", "stop"]);
const FIGURE_ATTRIBUTES = {
    svg: new Set(["xmlns", "class", "data-theme", "viewBox", "role", "aria-label"]),
    g: new Set(["class", "data-tone", "data-lit", "data-seamless", "data-pulse", "data-stamp", "data-picker", "data-selected", "data-part", "transform", "opacity"]),
    path: new Set(["class", "data-shade", "data-tone", "data-free", "data-dotted", "data-dashed", "data-flow", "d", "fill", "stroke", "stroke-width", "stroke-linecap", "style", "opacity"]),
    circle: new Set(["class", "cx", "cy", "r", "fill-opacity", "data-pulse", "style"]),
    ellipse: new Set(["cx", "cy", "rx", "ry", "fill", "opacity", "filter"]),
    text: new Set(["class", "data-tone", "transform", "font-size", "text-anchor", "aria-label"]),
    defs: new Set(),
    linearGradient: new Set(["id", "gradientUnits", "x1", "y1", "x2", "y2"]),
    radialGradient: new Set(["id", "cx", "cy", "r"]),
    filter: new Set(["id"]),
    feGaussianBlur: new Set(["stdDeviation"]),
    stop: new Set(["offset", "stop-opacity", "stop-color", "style"]),
};
const FIGURE_CHILDREN = {
    svg: new Set(["g", "path", "circle", "ellipse", "text", "defs"]),
    g: new Set(["g", "path", "circle", "ellipse", "text", "defs"]),
    defs: new Set(["linearGradient", "radialGradient", "filter"]),
    filter: new Set(["feGaussianBlur"]),
    linearGradient: new Set(["stop"]),
    radialGradient: new Set(["stop"]),
};
const FIGURE_EMPTY_TAGS = new Set(["path", "circle", "ellipse", "feGaussianBlur", "stop"]);
function validateFigureBody(source) {
    const stack = [];
    let rootSeen = false;
    let rootClosed = false;
    let offset = 0;
    const fail = () => { throw new TypeError("Figure body must be well-formed SVG using the passive anatomy vocabulary"); };
    const entitiesAreSafe = (value) => !/&(?!(?:amp|lt|gt|quot|apos|#\d+|#x[\da-f]+);)/i.test(value);
    while (offset < source.length) {
        const open = source.indexOf("<", offset);
        const textEnd = open < 0 ? source.length : open;
        const content = source.slice(offset, textEnd);
        if (!entitiesAreSafe(content)) fail();
        if (content.trim() && stack.at(-1) !== "text") fail();
        if (rootClosed && content.trim()) fail();
        if (open < 0) break;

        let end = open + 1;
        let quote = "";
        for (; end < source.length; end++) {
            const char = source[end];
            if (quote) {
                if (char === quote) quote = "";
            }
            else if (char === '"' || char === "'") quote = char;
            else if (char === ">") break;
        }
        if (end === source.length || quote) fail();
        const token = source.slice(open + 1, end);
        offset = end + 1;
        if (token.startsWith("!") || token.startsWith("?")) fail();

        const closing = token.startsWith("/");
        const selfClosing = !closing && token.endsWith("/");
        const inner = token.slice(closing ? 1 : 0, selfClosing ? -1 : undefined).trim();
        const nameMatch = /^([A-Za-z][A-Za-z0-9]*)/.exec(inner);
        if (!nameMatch) fail();
        const name = nameMatch[1];
        if (!FIGURE_TAGS.has(name)) fail();
        if (closing) {
            if (inner.slice(name.length).trim() || stack.pop() !== name) fail();
            if (name === "svg") rootClosed = true;
            continue;
        }
        if (FIGURE_EMPTY_TAGS.has(name) !== selfClosing) fail();
        if (!stack.length) {
            if (rootSeen || name !== "svg") fail();
            rootSeen = true;
        }
        else if (!FIGURE_CHILDREN[stack.at(-1)]?.has(name)) fail();

        const attributes = new Map();
        let rest = inner.slice(name.length);
        while (rest.trim()) {
            const match = /^\s+([A-Za-z_:][A-Za-z0-9_.:-]*)\s*=\s*("([^"<>]*)"|'([^'<>]*)')/.exec(rest);
            if (!match) fail();
            const key = match[1];
            const value = match[3] ?? match[4];
            if (!FIGURE_ATTRIBUTES[name].has(key) || attributes.has(key) || !entitiesAreSafe(value)) fail();
            attributes.set(key, value);
            rest = rest.slice(match[0].length);
        }
        const valueOf = (key) => attributes.get(key) ?? "";
        if (name === "svg") {
            const viewBox = valueOf("viewBox").trim().split(/[\s,]+/);
            if (valueOf("xmlns") !== "http://www.w3.org/2000/svg" || valueOf("role") !== "img" || !valueOf("aria-label").trim() || viewBox.length !== 4 || viewBox.some((part) => !/^[-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:e[-+]?\d+)?$/i.test(part))) fail();
        }
        if (name === "g" && valueOf("transform") && !/^translate\([-+0-9.eE\s,]+\)$/.test(valueOf("transform"))) fail();
        if ((name === "text") && valueOf("transform") && !/^translate\([-+0-9.eE\s,]+\)$/.test(valueOf("transform"))) fail();
        if (name === "path" && valueOf("style") && !/^stroke:url\(#iso-fade-[a-z0-9]+\)$/.test(valueOf("style"))) fail();
        if ((name === "circle" || name === "stop") && valueOf("style") && !/^(?:--pulse-at:\d+ms|stop-color:var\(--anatomy-[a-z0-9-]+\))$/.test(valueOf("style"))) fail();
        if ((name === "linearGradient" || name === "radialGradient" || name === "filter") && !/^[A-Za-z_][A-Za-z0-9_.-]*$/.test(valueOf("id"))) fail();
        if ((name === "path" || name === "ellipse") && valueOf("filter") && !/^url\(#[A-Za-z_][A-Za-z0-9_.-]*\)$/.test(valueOf("filter"))) fail();
        for (const attribute of ["fill", "stroke", "stop-color"]) {
            const paint = valueOf(attribute);
            if (paint && !/^(?:none|#[\da-f]{3,8}|url\(#[A-Za-z_][A-Za-z0-9_.-]*\))$/i.test(paint)) fail();
        }
        if (!selfClosing) stack.push(name);
        if (selfClosing && name === "svg") rootClosed = true;
    }
    if (!rootSeen || !rootClosed || stack.length) fail();
}
export function plateHtml(options) {
    if (!options || typeof options !== 'object' || Array.isArray(options)) throw new TypeError('Figure options must be an object');
    const unknown = Object.keys(options).filter(key => !['body', 'label'].includes(key));
    if (unknown.length) throw new TypeError(`Unsupported figure fields: ${unknown.join(', ')}`);
    const { body, label } = options;
    if (typeof body !== 'string' || !body.trim()) throw new TypeError('A figure needs its rendered body');
    validateFigureBody(body);
    if (label !== undefined && (typeof label !== 'string' || !label.trim())) throw new TypeError('A figure label must be nonempty text');
    return `<figure class="iso-figure"${label ? ` aria-label="${escape(label)}"` : ''}><div class="iso-plate">${body}</div></figure>`;
}

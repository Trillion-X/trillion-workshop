// Source artifact only. Parent 4 owns application and admitted qualification.
// No source input is replayed to reconstruct transaction metadata.
import test from 'node:test';
import assert from 'node:assert/strict';
import { sqliteHost } from '../src/local-store.mjs';
import { openRecords } from '../src/record-engine.mjs';
import { recordLogStore } from '../parts/record-log/do-work/record-log-store.mjs';
import { readAt } from '../../record-log/do-work/record-time.mjs';

const TABLE_MODEL = { value_kinds: { text: { is: 'string' } },
  kinds: [{ type: 'entry', table: true, properties: { title: 'text' } }] };
function raw(t, options = {}, reject = () => false) {
  const host = sqliteHost(':memory:'); t.after(() => host.db.close());
  const sql = { exec(query, ...args) {
    if (reject(query, args)) throw Error('original raw commit refused');
    return host.sql.exec(query, ...args);
  } };
  const open = () => recordLogStore(sql, { transaction: host.transaction, ...options });
  return { host, sql, open, store: open() };
}
function committed(store, result) {
  const rows = store.log({ transaction_id: result.transaction_id });
  const envelopes = rows.flatMap(row => row.envelopes);
  const ids = [...new Set(envelopes.map(envelope => envelope.id))];
  assert.deepEqual(result.written, ids, 'return exactly the roots in the actual committed transaction, including generated roots');
  assert.ok(result.previous_types instanceof Map);
  assert.deepEqual([...result.previous_types.keys()], ids, 'these fixtures have an authentic BEFORE for every committed root');
  for (const type of result.previous_types.values()) assert.ok(type === null || typeof type === 'string');
  return { rows, envelopes, ids };
}
function once(items, count) {
  return { [Symbol.iterator]() {
    assert.equal(++count.starts, 1, 'the canonical input may be traversed once');
    return items[Symbol.iterator]();
  } };
}

test('raw write returns its generated schema roots and their authentic known-null BEFORE', t => {
  const f = raw(t, { model: TABLE_MODEL, strict_model: true });
  const result = f.store.write([{ id: 'entry:one', type: 'entry', value: { title: 'First table row' } }]);
  const log = committed(f.store, result);
  const generated = log.envelopes.filter(envelope => envelope.type === 'table-schema-change');
  assert.ok(generated.length > 0, 'the actual table owner must create its schema evidence in this transaction');
  for (const envelope of generated) {
    assert.equal(envelope.prior, null);
    assert.equal(result.previous_types.has(envelope.id), true);
    assert.equal(result.previous_types.get(envelope.id), null);
  }
  assert.equal(result.previous_types.get('entry:one'), null);
  assert.equal(result.previous_types.has('entry:never-written'), false, 'unknown/unreported is not a known-null entry');
  assert.deepEqual(f.open().read('entry:one'), { title: 'First table row' });
});

test('applyChanges includes schema roots generated by the target rather than supplied by the input', t => {
  const source = raw(t), target = raw(t, { model: TABLE_MODEL, strict_model: true });
  const written = source.store.write([{ id: 'entry:copied', type: 'entry', value: { title: 'Carried table row' } }]);
  const supplied = committed(source.store, written).ids;
  const result = target.store.applyChanges(source.store.logAfter(null, { lazy: true }).rows);
  const emitted = committed(target.store, result);
  const generated = emitted.envelopes.filter(envelope => !supplied.includes(envelope.id));
  assert.ok(generated.some(envelope => envelope.type === 'table-schema-change'));
  for (const envelope of generated) assert.equal(result.previous_types.get(envelope.id), null);
  assert.deepEqual(target.open().read('entry:copied'), { title: 'Carried table row' });
});

test('repeated ID in one incoming transaction retains FIRST known-null BEFORE instead of intermediate type', t => {
  const source = raw(t), target = raw(t), id = 'note:repeated';
  source.store.write([{ id, type: 'note', value: { title: 'First' } }]);
  source.store.write([{ id, type: 'note', value: { title: 'Second' } }]);
  const result = target.store.applyChanges(source.store.logAfter(null, { lazy: true }).rows);
  const log = committed(target.store, result);
  assert.ok(log.envelopes.filter(envelope => envelope.id === id).length >= 2);
  assert.equal(result.previous_types.has(id), true);
  assert.equal(result.previous_types.get(id), null);
  assert.deepEqual(result.written, [id]);
  assert.deepEqual(target.open().read(id), { title: 'Second' });
});

test('repeated original type changes and removal retain the type from before the whole applyChanges call', t => {
  const source = raw(t), target = raw(t), id = 'record:transition';
  source.store.write([{ id, type: 'before', value: { title: 'Original' } }]);
  target.store.applyChanges(source.store.logAfter(null).rows);
  const position = source.store.lastLogId();
  source.store.write([{ id, type: 'middle', value: { title: 'Intermediate' } }]);
  source.store.write([{ id, type: 'after', value: { title: 'Later' } }]);
  source.store.write([{ id, type: 'after', value: null }]);
  const result = target.store.applyChanges(source.store.logAfter(position, { lazy: true }).rows);
  const log = committed(target.store, result);
  assert.ok(log.envelopes.filter(envelope => envelope.id === id).length >= 3);
  assert.equal(result.previous_types.get(id), 'before');
  assert.equal(target.store.typeOf(id), null);
  assert.equal(target.open().read(id), null);
});

test('a shared member created before envelope application reports its original absence, not its just-created type', t => {
  const f = raw(t);
  f.store.shareFields('kept-apart');
  const value = { one: { text: 'First retained version' }, two: { text: 'Second retained version' } };
  const result = f.store.write([{ id: 'kept-apart:one', type: 'kept-apart', value }]);
  const log = committed(f.store, result);
  const members = log.ids.filter(id => id.startsWith('shared:1f:'));
  assert.equal(members.length, 2, 'the actual shared owner creates both content-addressed roots');
  for (const id of members) {
    assert.equal(result.previous_types.has(id), true);
    assert.equal(result.previous_types.get(id), null, 'later annotation must not replace the pre-setRecord BEFORE');
  }
  assert.deepEqual(f.open().read('kept-apart:one'), value);
});

test('one-shot row and envelope streams are consumed once while metadata covers the actual emitted roots', t => {
  const source = raw(t), target = raw(t, { model: TABLE_MODEL, strict_model: true });
  source.store.write([{ id: 'entry:once', type: 'entry', value: { title: 'One shot' } }]);
  const rows = { starts: 0 }, envelopes = [];
  const feed = { *[Symbol.iterator]() {
    assert.equal(++rows.starts, 1);
    for (const row of source.store.logAfter(null, { lazy: true }).rows) {
      const count = { starts: 0 }; envelopes.push(count);
      yield { ...row, envelopes: once(row.envelopes, count) };
    }
  } };
  const result = target.store.applyChanges(feed);
  committed(target.store, result);
  assert.equal(rows.starts, 1);
  assert.ok(envelopes.length > 0);
  assert.ok(envelopes.every(count => count.starts === 1));
});

test('no-op writes and already-applied rows invent neither committed IDs nor known-null BEFORE entries', t => {
  const source = raw(t), target = raw(t);
  const row = { id: 'note:unchanged', type: 'note', value: { title: 'Same' } };
  source.store.write([row]);
  const through = source.store.lastLogId();
  const noop = source.store.write([row]);
  assert.deepEqual(noop.written, []);
  assert.deepEqual([...noop.previous_types], []);
  assert.equal(source.store.lastLogId(), through);
  target.store.applyChanges(source.store.logAfter(null).rows);
  const targetThrough = target.store.lastLogId();
  const repeat = target.store.applyChanges(source.store.logAfter(null, { lazy: true }).rows);
  assert.equal(repeat.applied, 0);
  assert.deepEqual(repeat.written, []);
  assert.deepEqual([...repeat.previous_types], []);
  assert.equal(target.store.lastLogId(), targetThrough);
});

test('a failed log insert rolls back generated schema/member mutations and retry starts with fresh BEFORE metadata', t => {
  let reject = false;
  const model = { value_kinds: { ...TABLE_MODEL.value_kinds, object: { is: 'object' } },
    kinds: [...TABLE_MODEL.kinds, { type: 'kept-apart', properties: { one: 'object' } }] };
  const f = raw(t, { model, strict_model: true }, query => reject && /^INSERT INTO record_log\b/.test(query));
  f.store.shareFields('kept-apart');
  const position = f.store.lastLogId();
  const changes = title => [{ id: 'entry:retry', type: 'entry', value: { title } },
    { id: 'kept-apart:retry', type: 'kept-apart', value: { one: { text: title } } }];
  reject = true;
  let escaped;
  assert.throws(() => { escaped = f.store.write(changes('Rejected')); }, /original raw commit refused/);
  assert.equal(escaped, undefined);
  reject = false;
  assert.equal(f.store.read('entry:retry'), null);
  assert.equal(f.open().read('entry:retry'), null);
  assert.equal(f.store.read('kept-apart:retry'), null);
  assert.deepEqual(f.open().ids('kept-apart/shared-member'), [], 'a pre-applied pending member cannot escape the failed transaction');
  assert.equal(f.store.lastLogId(), position);
  const result = f.store.write(changes('Committed'));
  const log = committed(f.store, result);
  assert.equal(result.previous_types.get('entry:retry'), null);
  assert.ok(log.envelopes.some(envelope => envelope.type === 'table-schema-change'));
  const member = log.ids.find(id => id.startsWith('shared:1f:'));
  assert.ok(member);
  assert.equal(result.previous_types.get(member), null, 'failed-attempt metadata cannot leak into the fresh committed write');
  assert.deepEqual(f.open().read('entry:retry'), { title: 'Committed' });
});

test('the existing frontier owner rolls actual generated roots and first-before back with a failed frontier update', t => {
  const a = sqliteHost(':memory:'), b = sqliteHost(':memory:');
  t.after(() => { a.db.close(); b.db.close(); });
  let reject = false;
  const sql = { exec(query, ...args) {
    if (reject && query.includes('UPDATE record_keys_meta') && query.includes('json_each(?)') && JSON.parse(args[0]).includes('record-change-revision:customer-database')) throw Error('original result frontier refused');
    return b.sql.exec(query, ...args);
  } };
  const source = openRecords(a.sql, { transaction: a.transaction });
  const target = openRecords(sql, { transaction: b.transaction });
  const id = 'customer-database:raw-inventory';
  source.write([{ id, type: 'customer-database', value: { name: 'Frontier', created_at: '2026-10-15T00:00:00.000Z' } }]);
  const clocks = ['customer-database', 'table-schema-change'];
  const before = target.durableRevisionOf(clocks), sequence = target.changeSeq();
  reject = true;
  assert.throws(() => target.applyChanges(source.logAfter(null, { lazy: true }).rows), /original result frontier refused/);
  reject = false;
  assert.equal(target.read(id), null);
  assert.equal(target.durableRevisionOf(clocks), before);
  assert.ok(target.changeSeq() > sequence, 'the existing journal invalidates earlier observer snapshots on rollback');
  assert.equal(target.changedSince(sequence), null, 'a failed write cannot vouch for rolled-back IDs');
  const cold = openRecords(b.sql, { transaction: b.transaction });
  assert.equal(cold.read(id), null);
  assert.equal(cold.durableRevisionOf(clocks), before, 'cold durable frontiers contain no failed import');
  const retrySequence = target.changeSeq();
  const result = target.applyChanges(source.logAfter(null, { lazy: true }).rows);
  const log = committed(target, result);
  assert.deepEqual(target.changedSince(retrySequence), log.ids);
  assert.equal(result.previous_types.get(id), null);
  assert.notEqual(target.durableRevisionOf(clocks), before);
});

test('metadata adds only IDs/types while original historical values and physical erasure stay with their existing owners', t => {
  const f = raw(t, { erasable: { note: ['secret'] } });
  const first = f.store.write([{ id: 'note:history', type: 'note', value: { title: 'One', secret: 'Private first words' } }], { application_time: '2026-10-15T01:00:00.000Z' });
  const second = f.store.write([{ id: 'note:history', type: 'note', value: { title: 'Two', secret: 'Private second words' } }], { application_time: '2026-10-15T02:00:00.000Z' });
  const firstLog = committed(f.store, first).rows.at(-1).id;
  const secondLog = committed(f.store, second).rows.at(-1).id;
  assert.equal(second.previous_types.get('note:history'), 'note');
  const metadata = JSON.stringify([first.written, [...first.previous_types], second.written, [...second.previous_types]]);
  assert.doesNotMatch(metadata, /Private|secret|One|Two/);
  // The existing readAt cut undoes the row at its exact ID too. Before the
  // second actual row, the first value is retained; before creation it is absent.
  assert.equal(readAt(f.store, 'note:history', firstLog).value, null);
  const historical = readAt(f.store, 'note:history', secondLog);
  assert.equal(historical.complete, true);
  assert.equal(historical.type, 'note');
  assert.deepEqual(historical.value, { title: 'One', secret: 'Private first words' });
  f.store.erase('note:history');
  const cold = f.open();
  assert.equal(cold.read('note:history'), null, 'the existing erasure owner removes the current record');
  const erasedHistory = readAt(cold, 'note:history', secondLog);
  assert.equal(erasedHistory.value?.secret, null, 'the same erased-field sentinel holds in actual retained history');
  assert.equal(erasedHistory.value?.title, 'One', 'physical erasure preserves the retained public history');
  assert.equal(second.previous_types.get('note:history'), 'note', 'returned type-only evidence does not reopen erased words');
});

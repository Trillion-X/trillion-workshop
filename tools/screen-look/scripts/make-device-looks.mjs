// scripts/make-device-looks.mjs
//
// PURPOSE
//   Carries Trillion's one look from where it is decided (screen-look's resolveScreenLookPalette and
//   resolveScreenLookButton over the themes in src/workspace/looks.json) into every device host that cannot run those
//   resolvers itself. Which hosts exist, which language each speaks and which files each needs are DATA
//   (parts/screen-look/device-hosts.json, its `generated` rows); this script only knows how to write a look in a
//   language (EMITTERS). A new device in a language already here is a row; a new language is one emitter.
//     node scripts/make-device-looks.mjs     writes every generated file a host row names (rows with written_by are
//                                            written by that build instead, through the same emitter)
//   test/one-design-every-device.test.mjs fails while any written file is stale.
//
// NON-NEGOTIABLE INVARIANTS
//   1. No value is decided here: every number and colour comes from resolveScreenLookPalette / resolveScreenLookButton,
//      and the nested-corner rule written into each palette is screen-look's nestedCorner / holdingCorner.
//   2. Every generated file is derived output; it is never edited by hand.
//   3. A colour this script cannot read as #rrggbb or rgba() stops it, so a theme never reaches a device half-read.
//   4. Every theme is written, so a host can wear any look a person picks by its id.
//
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveScreenLookButton, resolveScreenLookPalette } from 'trillion-workshop/tools/screen-look/read-data/resolve-screen-look-palette.js';
import { channels, paletteTokens } from 'trillion-workshop/tools/screen-look/read-data/device-look-tokens.js';

export const ROOT = dirname(dirname(dirname(fileURLToPath(import.meta.resolve('trillion-workshop/tools/workspace-screens/web/src/workspace/looks.json')))));
// The device rows moved with screen-look to the Workshop tool (tools/screen-look/device-hosts.json).
export const DEVICE_HOSTS = JSON.parse(readFileSync(fileURLToPath(import.meta.resolve('trillion-workshop/tools/screen-look/device-hosts.json')), 'utf8'));
const looks = JSON.parse(readFileSync(join(ROOT, 'src/workspace/looks.json'), 'utf8'));
const themes = looks.themes.map(row => row.payload);

// The CSS variables a button reads, from the same palette every web screen wears.
const BUTTON_VARIABLES = ['--radius-control', '--button-primary-bg', '--button-primary-bg-hover', '--button-primary-text', '--button-sheen', '--button-highlight', '--button-shadow', '--button-pressed-highlight', '--button-pressed-scale'];

function themeById(id) {
  const theme = themes.find(candidate => candidate.id === id);
  if (!theme) throw new Error(`src/workspace/looks.json has no theme ${id}`);
  return theme;
}

/** The `:root` block of a theme's button variables, for a stylesheet built ahead of time. */
export function buttonLookCss(themeId) {
  const palette = resolveScreenLookPalette(themeById(themeId));
  return `:root{${BUTTON_VARIABLES.map(name => `${name}:${palette[name]}`).join(';')}}\n`;
}

const number = value => String(Number(value.toFixed(4)));
function swiftColor(color) {
  const [red, green, blue, opacity] = channels(color);
  return `Color(.sRGB, red: ${number(red / 255)}, green: ${number(green / 255)}, blue: ${number(blue / 255)}, opacity: ${number(opacity)})`;
}
const swiftDictionary = object => (Object.keys(object).length ? `[${Object.entries(object).map(([key, value]) => `${JSON.stringify(key)}: ${JSON.stringify(value)}`).join(', ')}]` : '[:]');
const swiftLine = line => `Line(offsetY: ${line.offset_y}, blur: ${line.blur}, color: ${swiftColor(line.color)})`;

/** A theme's palette split into what every language can carry (device-look-tokens paletteTokens): its plain colours,
 *  its lengths in points, and its faces by role, first family first, which a host draws with the first one it has. */
export const themeTokens = theme => paletteTokens(resolveScreenLookPalette(theme));

const header = (path, what) => `// ${path}
//
// GENERATED by scripts/make-device-looks.mjs from the themes in src/workspace/looks.json, through screen-look's
// resolvers, for the hosts in parts/screen-look/device-hosts.json: the same look the web workspace, the Mac app and the
// Chrome extension wear. Never edit it by hand; change the theme and run \`node scripts/make-device-looks.mjs\`
// (test/one-design-every-device.test.mjs fails while stale).
//
${what}
`;

function swiftButtonTheme(theme) {
  const button = resolveScreenLookButton(theme);
  return `        "${theme.id}": ButtonLook(
            radius: ${button.radius},
            fill: ${swiftColor(button.fill)},
            fillPressed: ${swiftColor(button.fill_pressed)},
            text: ${swiftColor(button.text)},
            sheenTop: ${swiftColor(button.sheen.top)},
            sheenBottom: ${swiftColor(button.sheen.bottom)},
            border: ${swiftColor(button.border)},
            highlight: ${swiftLine(button.highlight)},
            contact: ${swiftLine(button.contact)},
            shadow: ${swiftLine(button.shadow)},
            pressedHighlight: ${swiftLine(button.pressed_highlight)},
            pressedScale: ${button.pressed_scale}
        ),`;
}

function swiftPaletteTheme(theme) {
  const { colors, lengths, faces } = themeTokens(theme);
  const colorRows = Object.entries(colors).map(([name, value]) => `            "${name}": ${swiftColor(value)},`).join('\n');
  const lengthRows = Object.entries(lengths).map(([name, value]) => `            "${name}": ${value},`).join('\n');
  const faceRows = Object.entries(faces).map(([role, families]) => `            "${role}": ${JSON.stringify(families)},`).join('\n');
  return `        "${theme.id}": LookPalette(colors: [
${colorRows}
        ], lengths: [
${lengthRows}
        ], faces: [
${faceRows}
        ]),`;
}

/** How a look is written in each language a host speaks, by the emitter id a generated row names. */
const EMITTERS = {
  'swift-button': (row, host) => `${header(row.path, `// A primary button: a rounded rectangle of \`radius\` (never a capsule) filled with \`fill\` (\`fillPressed\` while
// pressed) under a sheen from \`sheenTop\` to \`sheenBottom\`, a 1pt \`border\` a shade darker than the fill, \`text\`
// for its label, the \`highlight\` line along its top inside edge, and the \`contact\` line and soft \`shadow\` under it
// at rest; while pressed, the \`pressedHighlight\` line instead and a scale of \`pressedScale\`.`)}
import SwiftUI

struct ButtonLook {
    struct Line {
        let offsetY: CGFloat
        let blur: CGFloat
        let color: Color
    }

    let radius: CGFloat
    let fill: Color
    let fillPressed: Color
    let text: Color
    let sheenTop: Color
    let sheenBottom: Color
    let border: Color
    let highlight: Line
    let contact: Line
    let shadow: Line
    let pressedHighlight: Line
    let pressedScale: CGFloat

    /// The button look of the theme with this id in looks.json.
    static func theme(_ id: String) -> ButtonLook {
        guard let look = themes[id] else { preconditionFailure("looks.json has no theme \\(id)") }
        return look
    }

    static let themes: [String: ButtonLook] = [
${themes.map(swiftButtonTheme).join('\n')}
    ]
}
`,
  'swift-palette': (row, host) => `${header(row.path, `// Every theme's resolved palette: its plain colours and its lengths in points, by the palette's own names (the CSS
// variable without its dashes, e.g. "black-pure", "text-secondary", "radius-card"), and its faces by role ("display" for
// titles, "primary" for text: the families of --font-display and --font-primary, first first). \`deviceTheme\` is the
// look this host wears (src/workspace/looks.json start_with, the look every page starts with).`)}
import SwiftUI

struct LookPalette {
    let colors: [String: Color]
    let lengths: [String: CGFloat]
    let faces: [String: [String]]

    /// The look this device wears until the account says which look the person wears (ios/Shared/WornLook.swift), as
    /// src/workspace/looks.json start_with names it, the look every page and a new account start with.
    static let deviceTheme = "${host.theme}"

    /// The theme of each part of this host whose ground the platform fixes (its row's \`surfaces\`), by part.
    static let surfaceThemes: [String: String] = ${swiftDictionary(host.surfaces ?? {})}

    /// The palette of the theme with this id in looks.json.
    static func theme(_ id: String) -> LookPalette {
        guard let palette = themes[id] else { preconditionFailure("looks.json has no theme \\(id)") }
        return palette
    }

    /// A colour of this palette by its name; a name the themes do not have stops the app at launch, never silently.
    func color(_ name: String) -> Color {
        guard let value = colors[name] else { preconditionFailure("the look has no colour \\(name)") }
        return value
    }

    /// A length of this palette by its name.
    func length(_ name: String) -> CGFloat {
        guard let value = lengths[name] else { preconditionFailure("the look has no length \\(name)") }
        return value
    }

    /// The families of a face role ("display", "primary"), in the order a page tries them.
    func face(_ role: String) -> [String] {
        guard let families = faces[role] else { preconditionFailure("the look has no face \\(role)") }
        return families
    }

    /// A gap of \`steps\` spacing steps (\`space-unit\`), the rhythm every web gap is a whole number of.
    func gap(_ steps: CGFloat) -> CGFloat { length("space-unit") * steps }

    /// The corner of a shape \`gap\` in from a holder whose corner is \`outer\`: the holder's corner less the gap, never
    /// below zero, so the two curves run parallel (screen-look nestedCorner, nested-corners.css --corner-in).
    static func nested(in outer: CGFloat, gap: CGFloat) -> CGFloat { max(0, outer - gap) }

    /// The corner of a holder whose shape, \`gap\` in from its edge, has the corner \`held\` (screen-look holdingCorner).
    static func holding(_ held: CGFloat, gap: CGFloat) -> CGFloat { held + gap }

    static let themes: [String: LookPalette] = [
${themes.map(swiftPaletteTheme).join('\n')}
    ]
}
`,
  'css-button': (row, host) => buttonLookCss(host.theme),
};

/** Every file this script writes, as it must read now: [{ host, path, content }]. Rows written by a build are left out. */
export function deviceLookFiles() {
  const files = [];
  // A compiled host's first-launch look is the look every page and a new account start with (looks.json start_with):
  // one default, never a look a host row names for itself. At run time it wears the person's worn look.
  for (const host of DEVICE_HOSTS.hosts.map(row => ({ ...row, theme: looks.start_with }))) {
    for (const row of host.generated ?? []) {
      if (row.written_by) continue;
      const emit = EMITTERS[row.emitter];
      if (!emit) throw new Error(`device host ${host.id} names emitter ${row.emitter}, which scripts/make-device-looks.mjs does not have`);
      if (host.theme) themeById(host.theme);
      files.push({ host: host.id, path: row.path, content: emit(row, host) });
    }
  }
  return files;
}

/** The emitter ids this script can write, so a check can name a host whose language has none. */
export const EMITTER_IDS = Object.keys(EMITTERS);

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const file of deviceLookFiles()) {
    writeFileSync(join(process.cwd(), file.path), file.content); // host paths are the app repository's root paths: run it from there
    process.stdout.write(`wrote ${file.path} (${file.host})\n`);
  }
}

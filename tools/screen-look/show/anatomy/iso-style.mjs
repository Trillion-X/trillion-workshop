export const anatomyMaterialStyle = (name, quiet = false, { lit = false } = {}) => {
  const original = anatomyMaterialPalette[name] || anatomyMaterialPalette.metal;
  const c = quiet
    ? original.map((hex) => {
        const rgb = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
        const grey = rgb.reduce((a, b) => a + b) / 3;
        return `#${rgb.map((v) => Math.round(v * 0.35 + grey * 0.65).toString(16).padStart(2, '0')).join('')}`;
      })
    : original;
  const base = `--anatomy-face:${c[0]};--anatomy-top:${c[1]};--anatomy-shade-0:${c[2]};--anatomy-shade-1:${c[2]};--anatomy-shade-2:${c[0]};--anatomy-shade-3:${c[3]};--anatomy-lo:${c[2]};--anatomy-hi:${c[1]}`;
  return lit ? `${base};--anatomy-lit-top:${c[1]};--anatomy-lit-shade:${c[2]}` : base;
};

// tools/workflows/do-work/skill-from-workflow.mjs
//
// Makes a skill's SKILL.md from one workflow's rows, or checks that the file on disk is exactly what the rows make.
//
//   node do-work/skill-from-workflow.mjs --slug SLUG --live (--out FILE | --check FILE)
//   node do-work/skill-from-workflow.mjs --recipe RECIPE.json --steps STEPS.json (--out FILE | --check FILE)
//
// --live reads `record:workflow-recipe:SLUG` and the rows of `record:workflow-step:SLUG--*` through `trillion op @own-records`
// (the account's own list rows); the two files are those reads' JSON answers (records:read and records:list). --out writes
// the file; --check exits 1 and says so when the file is not the generated bytes, or is not there.

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { recipeFromRows } from '../read-data/recipe-rows.mjs';
import { skillFromWorkflow } from '../read-data/skill-from-workflow.mjs';

const args = process.argv.slice(2);
const flag = name => { const at = args.indexOf(name); return at < 0 ? undefined : args[at + 1]; };
const op = (method, input) => JSON.parse(execFileSync('trillion', ['op', '@own-records', method, JSON.stringify(input)], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }));

function rows() {
  if (args.includes('--live')) {
    const slug = flag('--slug');
    if (!slug) throw new Error('--live needs --slug.');
    const recipe = op('records:read', { id: `record:workflow-recipe:${slug}`, type: 'record:workflow-recipe' });
    // The door answers a page at a time with a `next` cursor: read every page, or a recipe is made from some of its steps.
    const steps = [];
    for (let after; ;) {
      const page = op('records:list', { type: 'record:workflow-step', prefix: `record:workflow-step:${slug}--`, limit: 256, ...(after ? { after } : {}) });
      steps.push(...page.records);
      if (!page.next || !page.records.length) break;
      after = page.next;
    }
    return { recipe, steps };
  }
  const recipe = JSON.parse(readFileSync(flag('--recipe'), 'utf8'));
  const steps = JSON.parse(readFileSync(flag('--steps'), 'utf8'));
  return { recipe, steps: steps.records ?? steps };
}

const { recipe, steps } = rows();
if (!recipe?.value) throw new Error('The recipe row holds no value: there is no such workflow.');
const text = skillFromWorkflow(recipeFromRows(recipe, steps));
if (flag('--out')) { writeFileSync(flag('--out'), text); process.stdout.write(`wrote ${flag('--out')} (${Buffer.byteLength(text)} bytes)\n`); }
else if (flag('--check')) {
  const path = flag('--check');
  if (!existsSync(path)) { process.stderr.write(`DRIFT: ${path} is not there; the workflow's rows make it.\n`); process.exit(1); }
  if (readFileSync(path, 'utf8') !== text) { process.stderr.write(`DRIFT: ${path} is not what the workflow's rows make; regenerate it with --out, never edit it.\n`); process.exit(1); }
  process.stdout.write(`${path} is what the rows make.\n`);
} else throw new Error('Give --out FILE or --check FILE.');

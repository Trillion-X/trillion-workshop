"""Readable views of pieces and drift reports. Generic: columns and sections come from the dimensions the
piece actually carries and from the registry's names."""
import json

from wt_core import BREAK, Registry
from wt_ops import runs, tok_index


def _t(x):
    if x is None:
        return ""
    m, s = divmod(float(x), 60)
    return f"{int(m)}:{s:05.2f}" if m else f"{s:.2f}"


def _cell(v):
    if isinstance(v, (list, dict)):
        v = json.dumps(v, ensure_ascii=False)
    return str(v).replace("|", "\\|").replace("\n", " ")


def _line_text(p, ln, reg, slot_style="template", idx=None):
    d = ln["dim"]
    idx = idx if idx is not None else tok_index(p)
    toks = [idx[i] for i in ln["tokens"] if i in idx and d in idx[i]["dims"]]
    out = []
    for kind, run in runs(toks, d):
        if kind == "KEEP":
            w = str(run[0]["dims"][d])
            out.append("\n" if w == BREAK else w)
            continue
        slot = p["slots"].get(run[0]["slot"], {})
        first, last = str(run[0]["dims"][d]), str(run[-1]["dims"][d])
        lead = first[:len(first) - len(first.lstrip("\"'“‘(["))]
        trail = last[len(last.rstrip(".,;:!?\"'”’)")):]
        if slot_style == "template":
            out.append(f"{lead}**[{slot.get('type', 'SLOT')}]**{trail}")
        elif slot_style == "fill":
            f = p.get("fills", {}).get(run[0]["slot"], {})
            out.append(f"«{first}»" if f.get("status") == "sourced" else first)
        else:
            out.append(first)
    return " ".join(out).replace(" \n ", "\n")


def _span(p, ln, idx=None):
    idx = idx if idx is not None else tok_index(p)
    ts = [idx[i].get("t") for i in ln["tokens"] if i in idx and idx[i].get("t") is not None]
    t1 = [idx[i].get("t1") for i in ln["tokens"] if i in idx and idx[i].get("t1") is not None]
    return f"{_t(min(ts))}-{_t(max(t1 or ts))}" if ts else ""


def text_dims(p, reg, words_only=False):
    seen = []
    for t in p["tokens"]:
        if words_only and not t.get("word"):
            continue
        for d in t["dims"]:
            if d not in seen and reg.is_text(d):
                seen.append(d)
    return seen


def _is_qualification(value):
    """A reader qualifies its measurement in notes with {reader, source_path, qualification}; the reader decides, no name is listed here."""
    return isinstance(value, dict) and "reader" in value and "qualification" in value


def _source_qualifications(p):
    qualifications = {k: v for k, v in p.get("notes", {}).items() if _is_qualification(v)}
    if not qualifications:
        return []
    lines = ["## Source qualifications", ""]
    for key, value in qualifications.items():
        lines.append(f"- `{key}` — reader `{value.get('reader')}`; source `{_cell(value.get('source_path', ''))}`. "
                     f"{_cell(value.get('qualification', ''))}")
    return lines + [""]


def render_template_md(p, reg=None):
    reg = reg or Registry.load(p.get("registry"))
    idx = tok_index(p)
    pc = p["piece"]
    n_slot_tok = sum(1 for t in p["tokens"] if t.get("mark") == "SLOT")
    measured = sorted({d for t in p["tokens"] for d in t["dims"]})
    L = [f"# Word-level template: {pc['id']} ({pc['medium']}, {pc.get('kind', 'reference')})", "",
         "Generated by `make_template.py`; do not edit by hand (edit the spec and rebuild).",
         f"Registry: `{p.get('registry')}`. Sources: " + ", ".join(f"{b['reader']} `{b['path']}`" + (" (MISSING)" if b.get("missing") else "")
                                                             for b in pc.get("built_from", [])) + ".",
         f"Tokens: {len(p['tokens'])} ({len(p['tokens']) - n_slot_tok} KEEP, {n_slot_tok} SLOT in {len(p['slots'])} slots). "
         f"Dimensions measured: {len(measured)}; pending: {len(p['pending'])}. Units: {len(p['units'])}.", "",
         "KEEP = a literal word or value copied from a listed source; its evidence qualifications still apply. **[TYPE]** = a slot: only a sourced value may go there.", ""]
    L += _source_qualifications(p)
    for d in text_dims(p, reg, words_only=True):
        row = reg.dim(d) or {}
        L += [f"## {row.get('name', d)} (`{d}`)", "", "| line | time | job | words |", "|---|---|---|---|"]
        for ln in [l for l in p["lines"] if l["dim"] == d]:
            L.append(f"| {ln['id']} | {_span(p, ln, idx)} | {_cell(ln.get('job') or '')} | {_cell(_line_text(p, ln, reg, idx=idx))} |")
        L.append("")
    if p["slots"]:
        L += ["## Slots", "", "| slot | type | what it does | rule | the creator's words or value | where |", "|---|---|---|---|---|---|"]
        slot_tokens = {}
        for t in p["tokens"]:
            if "slot" in t:
                slot_tokens.setdefault(t["slot"], []).append(t)
        for sid, s in p["slots"].items():
            toks = slot_tokens.get(sid, [])
            where = sorted({(t.get("line") or {}).get(d) for t in toks for d in t.get("slot_dims", []) if t.get("word")} - {None}
                           or {t.get("unit") for t in toks}, key=str)
            ref = []
            for t in toks:
                for d in t.get("slot_dims", []):
                    if d in t["dims"]:
                        ref.append(str(t["dims"][d]))
            L.append(f"| {sid} | {s.get('type')} | {_cell(s.get('note', ''))} | {s.get('rule', '')} | {_cell(' '.join(ref)[:160])} | {_cell(', '.join(map(str, where))[:120])} |")
        L.append("")
    regions = []
    region_tokens = {}
    for t in p["tokens"]:
        if not t.get("word") and t["dims"] and t.get("region") not in regions:
            regions.append(t.get("region"))
        if not t.get("word") and t["dims"]:
            region_tokens.setdefault(t.get("region"), []).append(t)
    for rg in regions:
        toks = region_tokens[rg]
        if not toks:
            continue
        cols = []
        for t in toks:
            for d in t["dims"]:
                if d not in cols:
                    cols.append(d)
        L += [f"## Region `{rg}` ({len(toks)} tokens)", "",
              "| token | unit | t | " + " | ".join(c.split(".", 1)[-1] for c in cols) + " |",
              "|---|---|---|" + "---|" * len(cols)]
        for t in toks:
            cells = []
            for c in cols:
                v = t["dims"].get(c, "")
                if t.get("mark") == "SLOT" and c in t.get("slot_dims", []):
                    v = f"**[{t.get('slot_type')}]** ({_cell(v)[:60]})"
                cells.append(_cell(v)[:90])
            L.append(f"| {t['id']} | {t.get('unit') or ''} | {_t(t.get('t'))} | " + " | ".join(cells) + " |")
        L.append("")
    if p["pending"]:
        L += ["## Pending dimensions (not measured for this piece)", "", "| dimension | why, and how it would be measured |", "|---|---|"]
        L += [f"| {x['dim']} | {_cell(x['reason'])} |" for x in p["pending"]]
        L.append("")
    if p.get("conflicts"):
        L += ["## Conflicting values (both kept)", ""] + [f"- {_cell(c)}" for c in p["conflicts"]] + [""]
    all_notes = p.get("notes", {})
    notes = {k: v for k, v in all_notes.items()
             if k != "drift" and not _is_qualification(v)}
    if notes:
        L += ["## Notes", ""] + [f"- {k}: {_cell(v)[:400]}" for k, v in notes.items()] + [""]
    return "\n".join(L)


def render_fill_md(p, fills_doc, reg=None, template_path="", fills_path=""):
    reg = reg or Registry.load(p.get("registry"))
    idx = tok_index(p)
    pc, F = p["piece"], p.get("fills", {})
    cnt = {k: sum(1 for f in F.values() if f["status"] == k) for k in ("sourced", "empty", "unsourced")}
    L = [f"# Fill: {pc.get('fill_of')} x {fills_doc.get('title', pc['id'])}", "",
         f"- Template: `{template_path}` (word-level; KEEP values retain their listed source qualifications and are not edited here).",
         f"- Fill values: `{fills_path}`. Made by `fill.py`.",
         f"- Slots: {cnt['sourced']} filled from a checked source, {cnt['empty']} empty, {cnt['unsourced']} offered without a valid source (left empty).",
         ""]
    L += _source_qualifications(p)
    for k in ("about", "truth_conditions"):
        if fills_doc.get(k):
            L += [f"**{k.replace('_', ' ').capitalize()}:** " + (" ".join(fills_doc[k]) if isinstance(fills_doc[k], list) else fills_doc[k]), ""]
    L += ["## Script", ""]
    for d in text_dims(p, reg):
        lines = [l for l in p["lines"] if l["dim"] == d]
        L += [f"`{d}` ({(reg.dim(d) or {}).get('name', d)}), one line per template line:", "", f"```dim:{d}"]
        L += [_line_text(p, ln, reg, "plain", idx) for ln in lines]
        L += ["```", ""]
    L += ["## Line view (« » = a sourced slot value; [TYPE: no source yet] = empty)", ""]
    for d in text_dims(p, reg, words_only=True):
        L += [f"`{d}`", "", "| line | time | job | words |", "|---|---|---|---|"]
        for ln in [l for l in p["lines"] if l["dim"] == d]:
            L.append(f"| {ln['id']} | {_span(p, ln, idx)} | {_cell(ln.get('job') or '')} | {_cell(_line_text(p, ln, reg, 'fill', idx))} |")
        L.append("")
    L += ["## Sources", "", "| slot | type | what it does | value | source(s) | check |", "|---|---|---|---|---|---|"]
    for sid, f in F.items():
        if f["status"] == "sourced":
            s = p["slots"][sid]
            plays = "; ".join(f"{m['clip']} {m['from']}-{m['to']} s" for m in f.get("moments") or [])
            L.append(f"| {sid} | {s.get('type')} | {_cell(s.get('note', ''))} | {_cell(f['value'])} | {_cell('; '.join(f['sources']))}"
                     + (f" (plays {_cell(plays)})" if plays else "")
                     + (f" ({_cell(f['note'])})" if f.get("note") else "") + f" | {_cell(f.get('check', ''))} |")
    L += ["", "## Empty slots", "", "| slot | type | what it does | why empty | what would fill it |", "|---|---|---|---|---|"]
    for sid, f in F.items():
        if f["status"] != "sourced":
            s = p["slots"][sid]
            why = "; ".join(f.get("why") or [])
            if f["status"] == "unsourced":
                why = f"offered {f.get('offered')!r} but: {why}"
            L.append(f"| {sid} | {s.get('type')} | {_cell(s.get('note', ''))} | {_cell(why)} | {_cell(f.get('needs') or '')} |")
    L.append("")
    decl = {"template": template_path, "fills": {k: {"value": f["value"], "sources": f["sources"], "derived": f.get("derived")}
                                                 for k, f in F.items() if f["status"] == "sourced"}}
    L += [f"<!-- word-template-fills {json.dumps(decl, ensure_ascii=False)} -->", ""]
    return "\n".join(L)


def render_drift_text(rep, lines="all", worst=5):
    s = rep["summary"]
    L = [f"DRIFT  template {rep['template']}  vs  {rep['target']}",
         f"KEEP preserved: {s['keep_preserved_pct']}% ({s['kept']} of {s['keep_total']} KEEP values)   "
         f"inserted (pure additions): {s['inserted']}   target words not matching the template (slot fills included): {s.get('new_words', 0)}   unsourced slot fills: {s['unsourced_fills']}"
         f" (reference values left in: {s['reference_values_left']})   sourced slot uses: {s['sourced_slots']}   empty slot uses: {s['empty_slots']}   slot uses dropped: {s.get('removed_slots', 0)}",
         "CHECK: " + ("PASS" if rep["check"]["pass"] else "FAIL - " + "; ".join(rep["check"]["fails"])), ""]
    L.append("per dimension:")
    for d, r in rep["dims"].items():
        L.append(f"  {d:<24} {r['pct']:>5}% KEEP preserved ({r['kept']}/{r['keep_total']}, pair={r['pair']})"
                 f"  deleted {r['deleted']}  replaced {r['replaced']}  inserted {r.get('inserted', 0)}  extra {r.get('extra', 0)}  excused {r['excused']}")
    if rep["not_measured_in_target"]:
        L.append(f"  not measured in the target (not judged): {', '.join(rep['not_measured_in_target'])}")
    if rep["extra_in_target"]:
        L.append(f"  in the target but not the template: {', '.join(rep['extra_in_target'])}")
    for u in rep["unknown"]:
        L.append(f"  UNKNOWN (reported, not judged): {u['dim']}: {u['why']}")
    if rep["pending_in_template"]:
        L.append(f"  pending in the template (cannot be judged yet): {len(rep['pending_in_template'])} dimensions")
    for d, r in rep["dims"].items():
        if not r.get("lines"):
            continue
        ranked = sorted([l for l in r["lines"] if l["keep_total"]], key=lambda l: (l["pct"], -l["keep_total"]))
        L += ["", f"WORST LINES ({d})"]
        for l in ranked[:worst]:
            L.append(f"  {l['line']} [{l.get('job') or ''}] {l['pct']}% kept ({l['kept']}/{l['keep_total']})")
            L.append(f"      {l['view']}")
        if lines == "all":
            L += ["", f"ANNOTATED LINES ({d})   [-deleted-]  {{+inserted+}}  <<sourced slot>>  [TYPE: empty]"]
            for l in r["lines"]:
                L.append(f"  {l['line']} {l['pct']:>5}%  {l['view']}")
    chg = [(d, c) for d, r in rep["dims"].items() for c in r["changes"]]
    if chg:
        L += ["", f"EVERY KEEP CHANGE ({len(chg)})"]
        for d, c in chg:
            by = f" -> {c['by']!r}" if c.get("by") else ""
            ex = f"   EXCUSED: {c['excused']}" if c.get("excused") else ""
            L.append(f"  {d} {c['line']} {c['op']}: {c['words']!r}{by}{ex}")
    if rep["slots"]:
        L += ["", "SLOTS"]
        for sid, st in rep["slots"].items():
            got = " ".join(str(x) for x in st.get("target", []) if x is not None)
            L.append(f"  {sid:<28} {st['status']:<15} {st.get('line') or ''}  {got[:100]!r}")
    if rep.get("conflicts"):
        L += ["", f"CONFLICTING VALUES IN THE TEMPLATE: {len(rep['conflicts'])} (both kept; see the template)"]
    return "\n".join(L)

// Writes assets/js/icons.js: the real lucide icon shapes (lucide-react 1.26.0 in the Trillion checkout this place reports, TRILLION_CHECKOUT) for every icon the
// slides use, as window.ICONS[name] = [[tag, attrs], ...] for a 24x24 viewBox. usage: node build-icons.mjs
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const DIR = path.dirname(new URL(import.meta.url).pathname);
const LUCIDE = path.join(process.env.TRILLION_CHECKOUT, 'node_modules/lucide-react/dist/esm/icons');      // in the Trillion checkout this place reports
const NAMES = ['list-checks', 'book-open-text', 'shopping-cart', 'printer', 'hand-helping', 'calendar-check', 'workflow', 'arrow-right', 'store', 'check', 'user-round', 'circle-check', 'loader-circle', 'calendar-clock', 'camera', 'clock', 'map-pin', 'wallet', 'bell', 'bot', 'circle-dashed'];
const out = {};
for (const n of NAMES) {
  const src = fs.readFileSync(path.join(LUCIDE, `${n}.mjs`), 'utf8');
  const m = src.match(/const __iconNode = (\[[\s\S]*?\]);\n/);
  const node = Function(`return ${m[1]}`)();          // a plain array literal of [tag, attrs]
  out[n] = node.map(([tag, a]) => [tag, Object.fromEntries(Object.entries(a).filter(([k]) => k !== 'key'))]);
}
fs.writeFileSync(path.join(DIR, 'assets/js/icons.js'), `// generated by build-icons.mjs from lucide-react 1.26.0 (ISC)\nwindow.ICONS=${JSON.stringify(out)};\n`);
console.log('icons:', Object.keys(out).join(', '));

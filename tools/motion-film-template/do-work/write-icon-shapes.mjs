// Writes assets/js/icons.js: the real lucide icon shapes (lucide-react 1.26.0 in the Trillion checkout this computer reports, TRILLION_CHECKOUT) for every icon the
// slides use, as window.ICONS[name] = [[tag, attrs], ...] for a 24x24 viewBox. usage: node build-icons.mjs
//
// tools/motion-film-template/do-work/write-icon-shapes.mjs: the film's build-icons.mjs with what it fixed taken from
// one JSON request on stdin: { "names": [...], "icons_dir": "<lucide-react>/dist/esm/icons" (or TRILLION_CHECKOUT set),
// "out": "<film>/assets/js/icons.js" (optional: without it the text is answered), "note", "by" }. One answer line.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { text } from 'node:stream/consumers';

export function iconShapes(src, n) {
  const m = src.match(/const __iconNode = (\[[\s\S]*?\]);\n/);
  if (!m) throw new Error(`${n}: no __iconNode in the icon module; is icons_dir lucide-react's dist/esm/icons?`);
  const node = Function(`return ${m[1]}`)();          // a plain array literal of [tag, attrs]
  return node.map(([tag, a]) => [tag, Object.fromEntries(Object.entries(a).filter(([k]) => k !== 'key'))]);
}

export function iconsFile({ icons_dir, names, note = 'lucide-react (ISC)', by = 'tools/motion-film-template write-icon-shapes' }) {
  let dir = icons_dir;
  if (!dir && process.env.TRILLION_CHECKOUT) {
    const LUCIDE = path.join(process.env.TRILLION_CHECKOUT, 'node_modules/lucide-react/dist/esm/icons');      // in the Trillion checkout this computer reports
    dir = LUCIDE;
  }
  const LUCIDE = dir;
  const NAMES = names;
  if (!LUCIDE || !Array.isArray(NAMES) || !NAMES.length) throw new Error('Give icons_dir (lucide-react\'s dist/esm/icons folder) and names (the icon names the film uses).');
  const out = {};
  for (const n of NAMES) {
    if (!fs.existsSync(path.join(LUCIDE, `${n}.mjs`))) throw new Error(`no icon named ${n} in ${LUCIDE}`);
    const src = fs.readFileSync(path.join(LUCIDE, `${n}.mjs`), 'utf8');
    const m = src.match(/const __iconNode = (\[[\s\S]*?\]);\n/);
    if (!m) throw new Error(`${n}: no __iconNode in the icon module; is icons_dir lucide-react's dist/esm/icons?`);
    const node = Function(`return ${m[1]}`)();          // a plain array literal of [tag, attrs]
    out[n] = node.map(([tag, a]) => [tag, Object.fromEntries(Object.entries(a).filter(([k]) => k !== 'key'))]);
  }
  return { text: `// generated by ${by} from ${note}\nwindow.ICONS=${JSON.stringify(out)};\n`, names: Object.keys(out) };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    const request = JSON.parse((await text(process.stdin)) || '{}');
    const { text: file, names } = iconsFile(request);
    if (request.out) fs.writeFileSync(request.out, file);
    console.log(JSON.stringify({ result: { names, bytes: Buffer.byteLength(file), ...(request.out ? { out: request.out } : { text: file }) } }));
  } catch (error) {
    console.log(JSON.stringify({ error: error.message }));
    process.exitCode = 1;
  }
}

const folder = fileURLToPath(new URL('..', import.meta.url));
test('icon shapes are read from lucide modules, the React key dropped, and a missing icon is refused', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'icons-'));
  try {
    fs.writeFileSync(path.join(dir, 'check.mjs'), 'import x from "../x.mjs";\n\nconst __iconNode = [["path", { d: "M20 6 9 17l-5-5", key: "abc" }]];\nconst Check = x("check", __iconNode);\n');
    fs.writeFileSync(path.join(dir, 'dot.mjs'), 'const __iconNode = [\n  ["circle", { cx: "12", cy: "12", r: "1", key: "q" }],\n  ["path", { d: "M1 1", key: "z" }]\n];\n');
    const file = iconsFile({ icons_dir: dir, names: ['check', 'dot'], note: 'made-up icons (ISC)' });
    assert.equal(file.text, '// generated by tools/motion-film-template write-icon-shapes from made-up icons (ISC)\nwindow.ICONS={"check":[["path",{"d":"M20 6 9 17l-5-5"}]],"dot":[["circle",{"cx":"12","cy":"12","r":"1"}],["path",{"d":"M1 1"}]]};\n');
    assert.throws(() => iconsFile({ icons_dir: dir, names: ['nope'] }), /no icon named nope/);
    assert.throws(() => iconsFile({ names: ['check'] }), /icons_dir/);
    assert.throws(() => iconShapes('export {}', 'x'), /no __iconNode/);
    const out = path.join(dir, 'icons.js');
    const run = spawnSync(process.execPath, [path.join(folder, 'do-work', 'write-icon-shapes.mjs')], { input: JSON.stringify({ icons_dir: dir, names: ['dot'], out }), encoding: 'utf8' });
    assert.equal(run.status, 0, run.stdout);
    assert.deepEqual(JSON.parse(run.stdout.trim()).result.names, ['dot']);
    assert.match(fs.readFileSync(out, 'utf8'), /^\/\/ generated by/);
    // with no icons_dir, the lucide-react package of the checkout TRILLION_CHECKOUT names (the film script's way)
    const checkout = path.join(dir, 'checkout');
    fs.mkdirSync(path.join(checkout, 'node_modules/lucide-react/dist/esm/icons'), { recursive: true });
    fs.copyFileSync(path.join(dir, 'dot.mjs'), path.join(checkout, 'node_modules/lucide-react/dist/esm/icons/dot.mjs'));
    const saved = process.env.TRILLION_CHECKOUT;
    process.env.TRILLION_CHECKOUT = checkout;
    try { assert.deepEqual(iconsFile({ names: ['dot'] }).names, ['dot']); } finally { if (saved === undefined) delete process.env.TRILLION_CHECKOUT; else process.env.TRILLION_CHECKOUT = saved; }
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('the rows name scripts that exist, read only their own settings rows, and name no film or person', () => {
  const rows = JSON.parse(fs.readFileSync(path.join(folder, 'tool-rows.json'), 'utf8')).records.map(r => r.payload);
  assert.deepEqual(rows.map(r => r.id), ['tool:plan-a-motion-films-soundtrack-premix', 'tool:premix-a-motion-films-soundtrack',
    'tool:write-the-icon-shapes-a-motion-film-uses']);
  for (const r of rows) {
    const named = JSON.stringify(r.invoke).match(/motion-film-template\/(do-work|read-data)\/[\w.-]+/g) ?? [];
    for (const n of named) assert.ok(fs.existsSync(path.join(folder, n.replace('motion-film-template/', ''))), n);
  }
  assert.deepEqual(rows[0].invoke.records.rights, [{ kind: 'record:setting', prefix: 'record:setting:motion-film-template~', operations: ['records:read'] }]);
  const all = ['tool-rows.json', 'README.md', 'do-work/premix_soundtrack.py', 'do-work/write-icon-shapes.mjs'].map(f => fs.readFileSync(path.join(folder, f), 'utf8')).join('\n');
  assert.doesNotMatch(all, /\/Users\//);
});

test('the soundtrack premix keeps its promises (Python tests on a made-up film)', () => {
  const run = spawnSync('python3', ['-I', path.join(folder, 'test', 'test_premix_soundtrack.py')], { encoding: 'utf8' });
  assert.equal(run.status, 0, run.stderr.slice(-3000));
  assert.match(run.stderr, /Ran \d+ tests/);
});

test('the premix reads its film\'s settings row by id through the records door, under the request\'s own settings', async () => {
  const ID = 'record:setting:motion-film-template~film~sample-film';
  const ROW = { name: 'motion-film-template for sample-film', tool: 'tool:premix-a-motion-films-soundtrack', scope_kind: 'film', scope_id: 'sample-film',
    settings: JSON.stringify({ duration: 4, after_mix: 'loudnorm=I=-14' }), from: 'made-up/mix.py@0000000', status: 'active' };
  const fake = await startFakeDoor({ rights: [{ kind: 'record:setting', prefix: 'record:setting:motion-film-template~', operations: ['records:read'] }], records: [{ id: ID, type: 'record:setting', value: ROW }] });
  try {
    let printed = '';
    const out = new Writable({ write(chunk, _e, done) { printed += chunk; done(); } });
    const request = { cue_sheet: [{ t: 0.5, sound: 'tick', gain_db: -9 }], film_folder: 'f', sound_folder: 's', settings_record: ID, settings: { after_mix: 'loudnorm=I=-16' } };
    const code = await runWithSettings(['--folder', 'motion-film-template', '--', 'python3', '-I', path.join(folder, 'do-work', 'premix_soundtrack.py')],
      { stdin: Readable.from([JSON.stringify(request)]), door: openRecordsDoor({ descriptor: fake.descriptor }), out });
    assert.equal(code, 0, printed);
    const { result } = JSON.parse(printed.trim().split('\n').at(-1));
    assert.equal(result.DUR, 4);
    assert.match(result.premix[result.premix.indexOf('-filter_complex') + 1], /\[mixed\]loudnorm=I=-16\[pre\]$/);
    assert.equal(result.settings_from.id ?? result.settings_from, result.settings_from.id ?? ID);
  } finally { await fake.close?.(); }
});

"""Place each Watch Later video into playlists, from the person's sort settings. Pure: reads nothing, writes nothing.

Ported from launch-video tools/yt-library/plan_sort.py, whose channels were a list in the code and whose rules were files
beside it; here both are the person's settings, given in. A channel's settings say how it is sorted:
- "sort": "rules", with "rules": {"max_per_video", "hold_back" (a regular expression over titles), "hold_back_reason",
  "rules": [{"key", "title", "description", "channels", "strong", "weak"}]}. A channel name the "channels" expression
  matches whole scores 3, a "strong" title match 3, a "weak" one 1. A video goes to every playlist that scores 3 or more,
  at most max_per_video of them, highest first (ties to the earlier rule); with none, to its best weak match, low confidence.
- "sort": "hand-made" (or "manual"), with "playlists": [{"key", "title", "description", "videos": [[video id, reason], ...]}],
  kept in that order.
"""
import re

PLAN_HEADER = ['# Watch Later sort plan\n', 'Generated by `tools/sort-youtube-watch-later-into-playlists/do-work/plan_sort.py`. Watch Later lists are never modified; every video is ADDED as a copy to public playlists on the same channel. Items marked LOW are low confidence. Within a playlist, videos are ordered by view count, highest first, except hand-ordered lists which keep the order shown.\n']
HOLD_BACK_REASON = 'held back by the sort settings: not published on a public playlist without the person deciding'


class SettingsError(Exception):
    pass


def views_n(v):
    m = re.match(r'([\d.,]+)\s*([KMB]?)\s+views', v or '')
    if not m: return 0
    return float(m.group(1).replace(',', '')) * {'': 1, 'K': 1e3, 'M': 1e6, 'B': 1e9}[m.group(2)]

def classify_rules(cfg, items):
    cfg = {**cfg, 'hold_back': cfg.get('hold_back') or r'(?!)'}  # no hold_back holds nothing back
    reason = cfg.get('hold_back_reason') or HOLD_BACK_REASON
    hold = re.compile(cfg['hold_back'])
    rules = []
    for r in cfg['rules']:
        rules.append((r, re.compile(r['channels'].lstrip('^')) if r.get('channels') else None,
                      re.compile(r'\b(?:' + r['strong'] + ')') if r.get('strong') else None, re.compile(r'\b(?:' + r['weak'] + ')') if r.get('weak') else None))
    pls = {r['key']: {'key': r['key'], 'title': r['title'], 'description': r['description'], 'items': []} for r in cfg['rules']}
    unsorted, held = [], []
    for it in items:
        if hold.search(it['title'] or ''):
            held.append({'id': it['id'], 'title': it['title'], 'reason': reason}); continue
        sc = []
        for idx, (r, ch, st, wk) in enumerate(rules):
            s, why = 0, []
            if ch and it['channel'] and ch.fullmatch(it['channel']): s += 3; why.append('channel ' + it['channel'])
            if st:
                m = st.search(it['title'] or '')
                if m: s += 3; why.append('title "' + m.group(0).strip() + '"')
            if wk:
                m = wk.search(it['title'] or '')
                if m: s += 1; why.append('weak title "' + m.group(0).strip() + '"')
            if s: sc.append((s, -idx, r['key'], '; '.join(why)))
        sc.sort(reverse=True)
        sc = [x for x in sc if x[0] >= 3][:cfg['max_per_video']] or sc[:1]
        if not sc: unsorted.append(it); continue
        for s, _, key, why in sc:
            conf = 'high' if s >= 6 else 'medium' if s >= 3 else 'low'
            pls[key]['items'].append({'id': it['id'], 'url': it['url'], 'title': it['title'], 'channel': it['channel'], 'views': it['views'],
                                      'reason': why, 'confidence': conf, '_v': views_n(it['views'])})
    return items, pls, unsorted, held

def classify_manual(m, items):
    byid = {i['id']: i for i in items}
    pls = {}
    for p in m['playlists']:
        pls[p['key']] = {'key': p['key'], 'title': p['title'], 'description': p['description'], 'items': []}
        for vid, reason in p['videos']:
            if vid not in byid:
                raise SettingsError(f'hand-made playlist {p["key"]} names video {vid}, which is not in this Watch Later: read the channel again or take it out of the settings')
            it = byid[vid]
            pls[p['key']]['items'].append({'id': vid, 'url': it['url'], 'title': it['title'], 'channel': it['channel'], 'views': it['views'], 'reason': reason, 'confidence': 'high', '_v': 0, '_keep': True})
    placed = {v for p in m['playlists'] for v, _ in p['videos']}
    return items, pls, [i for i in items if i['id'] not in placed], []


def classify(ch, items):
    mode = ch.get('sort')
    if mode == 'rules':
        return classify_rules(ch['rules'], items)
    if mode in ('hand-made', 'manual'):
        return classify_manual(ch, items)
    raise SettingsError(f'channel {ch.get("slug")} has sort {mode!r}: use "rules" or "hand-made", or leave sort out to only read it')


def make_plan(settings, watch_later, generated=None):
    """settings: {"channels": [...]}; watch_later: {slug: [items]} for each sorted channel. Answers (plan, the plan page's lines).
    A channel without sort is only read, never sorted."""
    channels = {c['slug']: c for c in settings.get('channels', []) if c.get('sort')}
    for slug in channels:
        if slug not in watch_later:
            raise SettingsError(f'no Watch Later for channel {slug}: read it first with do-work/read_channel.py')
    ACCOUNTS = [(c['slug'], c['label'], c.get('authuser', 0), c.get('page_id'), c.get('email'), c['sort']) for c in channels.values()]
    out = {'generated': __import__('time').strftime('%Y-%m-%dT%H:%M:%S'), 'accounts': []}
    if generated: out['generated'] = generated
    md = list(PLAN_HEADER)
    for slug, label, au, pid, email, mode in ACCOUNTS:
        items, pls, uns, held = classify(channels[slug], watch_later[slug])
        plist = []
        for p in pls.values():
            if not p['items']: continue
            if not any(i.get('_keep') for i in p['items']): p['items'].sort(key=lambda i: -i['_v'])
            for i in p['items']: i.pop('_v', None); i.pop('_keep', None)
            plist.append(p)
        plist.sort(key=lambda p: -len(p['items']))
        out['accounts'].append({'slug': slug, 'channel': label, 'authuser': au, 'page_id': pid, 'email': email, 'watch_later_count': len(items),
                                'playlists': plist, 'unsorted': [{'id': u['id'], 'title': u['title'], 'channel': u['channel']} for u in uns], 'held_back': held})
        if channels[slug].get('sign_in_as'): out['accounts'][-1]['sign_in_as'] = channels[slug]['sign_in_as']
        sorted_ids = {i['id'] for p in plist for i in p['items']}
        md.append(f'\n## {label} ({email}) : Watch Later {len(items)}; sorted into playlists {len(sorted_ids)}; unsorted {len(uns)}; held back {len(held)}\n')
        for p in plist:
            low = sum(1 for i in p['items'] if i['confidence'] == 'low')
            md.append(f'\n### {p["title"]} ({len(p["items"])} videos, {low} low confidence)\n{p["description"]}\n')
            for n, i in enumerate(p['items'], 1):
                md.append(f'{n}. {"**LOW** " if i["confidence"]=="low" else ""}[{i["title"]}]({i["url"]}) ({i["channel"]}): {i["reason"]}')
        if held:
            md.append('\n### Held back (not placed on a public playlist)\n'); md += [f'- {h["title"]}: {h["reason"]}' for h in held]
        if uns:
            md.append('\n### Unsorted (no confident fit; left only in Watch Later)\n'); md += [f'- {u["title"]} ({u["channel"]})' for u in uns]
    return out, md

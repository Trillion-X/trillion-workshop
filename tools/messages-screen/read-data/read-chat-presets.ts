/**
 * A preset action that users can trigger to run a predefined task.
 * Presets are stored in TOML format and parsed at startup.
 */
export interface Preset {
  /** Unique identifier for this preset (e.g., "run-task", "refactor") */
  id: string;

  /** Human-readable label (e.g., "Run Task", "Refactor") */
  label: string;

  /** Lucide React icon name (e.g., "play", "wrench", "zap") */
  icon: string;

  /** Category for grouping in UI and filtering */
  category: 'task' | 'analysis' | 'system' | 'project';

  /** Full prompt sent to the LLM when this preset is triggered */
  prompt: string;

  /** Short description displayed in UI (one sentence) */
  description: string;

  /** Optional keyboard shortcut (e.g., "Cmd+Shift+R") */
  shortcut?: string;

  /** Whether this preset is enabled and available for use */
  enabled: boolean;

  /** Sort order (lower number = higher in list) */
  order: number;

  /** Whether this preset was auto-generated by the system (vs user-created) */
  auto_generated?: boolean;

  /** Confidence score (0-1) for auto-generated presets — quality indicator */
  confidence?: number;
}

function valueToString(value: unknown): string {
  return typeof value === 'string' ? value : value == null ? '' : String(value);
}

function valueToBoolean(value: unknown): boolean {
  if (typeof value === 'boolean') return value;
  if (typeof value === 'string') return value === 'true';
  return false;
}

function valueToNumber(value: unknown, fallback: number): number {
  if (typeof value === 'number' && Number.isFinite(value)) return value;
  if (typeof value === 'string') {
    const parsed = Number(value);
    if (Number.isFinite(parsed)) return parsed;
  }
  return fallback;
}

function valueToCategory(value: unknown): Preset['category'] {
  return value === 'task' || value === 'analysis' || value === 'system' || value === 'project'
    ? value
    : 'task';
}

function rowsBySubject(raw: unknown): Map<string, Record<string, unknown>> {
  const grouped = new Map<string, Record<string, unknown>>();
  if (!Array.isArray(raw)) return grouped;

  for (const entry of raw) {
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) continue;
    const row = entry as Record<string, unknown>;
    const subjectId = typeof row.subject_id === 'string' ? row.subject_id : '';
    const propertyId = typeof row.property_id === 'string' ? row.property_id : '';
    if (!subjectId || !propertyId) continue;
    const current = grouped.get(subjectId) ?? { id: subjectId };
    current[propertyId.split(':').pop() ?? propertyId] = row.value;
    grouped.set(subjectId, current);
  }

  return grouped;
}

function convertPresetRow(row: Record<string, unknown>, index: number): Preset {
  return {
    id: valueToString(row.id),
    label: valueToString(row.label),
    icon: valueToString(row.icon) || 'message-square',
    category: valueToCategory(row.category),
    prompt: valueToString(row.prompt),
    description: valueToString(row.description),
    shortcut: valueToString(row.shortcut) || undefined,
    enabled: row.enabled == null ? true : valueToBoolean(row.enabled),
    order: valueToNumber(row.order, index),
    auto_generated: row.auto_generated == null ? undefined : valueToBoolean(row.auto_generated),
    confidence: row.confidence == null ? undefined : valueToNumber(row.confidence, 0),
  };
}

export function decodeChatPresetsFeed(raw: unknown): Preset[] {
  return Array.from(rowsBySubject(raw).values())
    .map(convertPresetRow)
    .filter((preset) => preset.label && preset.prompt)
    .sort((left, right) => left.order - right.order || left.label.localeCompare(right.label));
}
